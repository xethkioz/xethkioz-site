import fs from 'node:fs'
import path from 'node:path'

const root = process.cwd()
const sourcePath = path.join(root, 'src', 'xethkioz-redesign.css')
const generatedDir = path.join(root, 'src', 'generated')
const corePath = path.join(generatedDir, 'xethkioz-core.css')
const greenNodePath = path.join(generatedDir, 'green-node-shell.css')

const GREEN_START = '@keyframes xk-access-shake'
const GREEN_END = '/* Anime portals: Games and Memes intentionally use different visual grammars. */'

function writeIfChanged(filePath, content) {
  if (fs.existsSync(filePath) && fs.readFileSync(filePath, 'utf8') === content) return false
  fs.writeFileSync(filePath, content)
  return true
}

if (!fs.existsSync(sourcePath)) {
  throw new Error(`CSS source not found: ${path.relative(root, sourcePath)}`)
}

const source = fs.readFileSync(sourcePath, 'utf8')
const greenStart = source.indexOf(GREEN_START)
const greenEnd = source.indexOf(GREEN_END, greenStart)

if (greenStart < 0 || greenEnd < 0 || greenEnd <= greenStart) {
  throw new Error('Green Node CSS markers are missing or out of order.')
}

const greenNodeBlock = source.slice(greenStart, greenEnd).trim()
const coreBlock = `${source.slice(0, greenStart).trimEnd()}\n\n${source.slice(greenEnd).trimStart()}`.trim()

if (!greenNodeBlock.includes('.xk-green-shell') || !greenNodeBlock.includes('.xk-green-content')) {
  throw new Error('Green Node CSS extraction did not include the expected shell contract.')
}

if (coreBlock.includes('.xk-green-shell') || coreBlock.includes('.xk-green-access-sequence')) {
  throw new Error('Green Node route selectors leaked back into the global core.')
}

fs.mkdirSync(generatedDir, { recursive: true })

const coreOutput = `/* AUTO-GENERATED by scripts/split-redesign-css.mjs. Edit src/xethkioz-redesign.css instead. */\n${coreBlock}\n`
const greenNodeOutput = `/* AUTO-GENERATED route CSS. Source: src/xethkioz-redesign.css */\n${greenNodeBlock}\n`

const coreChanged = writeIfChanged(corePath, coreOutput)
const greenChanged = writeIfChanged(greenNodePath, greenNodeOutput)

console.log(JSON.stringify({
  sourceBytes: Buffer.byteLength(source),
  globalCoreBytes: Buffer.byteLength(coreOutput),
  greenNodeBytes: Buffer.byteLength(greenNodeOutput),
  globalReductionBytes: Buffer.byteLength(source) - Buffer.byteLength(coreOutput),
  wrote: {
    core: coreChanged,
    greenNode: greenChanged,
  },
}))
